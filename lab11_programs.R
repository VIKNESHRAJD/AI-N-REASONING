# lab11_programs.R
# Generated helper: extract R code snippets from "Lab 11 Answers.pdf" in the repo and
# combine them into a single R file. This script will try to extract R-like lines
# heuristically and write them out to "lab11_programs_extracted.R" in the repo root.
#
# Notes:
# - It uses the 'pdftools' package to convert the PDF to text. Install it if needed.
# - Extraction is best-effort: if the PDF uses images or an unusual layout, manual
#   review may still be required.
# - If you want me to instead commit the fully-extracted R code directly, reply
#   and I'll run a manual extraction and update this file with the final code.

pdf_url <- "https://raw.githubusercontent.com/VIKNESHRAJD/AI-N-REASONING/main/Lab%2011%20Answers.pdf"
out_file <- "lab11_programs_extracted.R"

if (!requireNamespace("pdftools", quietly = TRUE)) {
  install.packages("pdftools", repos = "https://cloud.r-project.org")
}

library(pdftools)

cat("Reading PDF from:", pdf_url, "\n")

# Try to download and read PDF. If download fails, try local file path.
txt <- NULL
try({
  tmpf <- tempfile(fileext = ".pdf")
  download.file(pdf_url, tmpf, quiet = TRUE, mode = "wb")
  txt <- pdf_text(tmpf)
  unlink(tmpf)
}, silent = TRUE)

if (is.null(txt)) {
  if (file.exists("Lab 11 Answers.pdf")) {
    txt <- pdf_text("Lab 11 Answers.pdf")
  } else {
    stop("Could not download or find 'Lab 11 Answers.pdf'. Please ensure the file exists or update pdf_url.")
  }
}

# Combine pages and split into lines
all_text <- paste(txt, collapse = "\n\f\n")
lines <- unlist(strsplit(all_text, "\n"))

# Heuristic: keep blocks that look like R code. We'll mark a line as 'code-like' if
# it contains common R tokens: '<-' assignment, 'library(', 'read.csv', 'function(',
# '#', '%>%', 'plot(', 'ggplot', 'data.frame', or ends with ')' while containing '<-'.

is_code_line <- function(line) {
  line2 <- trimws(line)
  if (nchar(line2) == 0) return(FALSE)
  patterns <- c("<-", "library\\(", "read\\.csv", "function\\(", "#",
                "%>%", "plot\\(", "ggplot\\(", "data\.frame", "readLines\\(")
  for (p in patterns) {
    if (grepl(p, line2, perl = TRUE)) return(TRUE)
  }
  # also if line starts with typical R prompt '>' (from examples)
  if (grepl("^>\\s*", line2)) return(TRUE)
  FALSE
}

code_flags <- vapply(lines, is_code_line, logical(1))

# Group contiguous code-like lines into blocks and keep blocks with >=1 lines.
blocks <- list()
if (any(code_flags)) {
  in_block <- FALSE
  cur <- c()
  for (i in seq_along(lines)) {
    if (code_flags[i]) {
      cur <- c(cur, lines[i])
      in_block <- TRUE
    } else {
      if (in_block) {
        blocks[[length(blocks) + 1]] <- cur
        cur <- c()
        in_block <- FALSE
      }
    }
  }
  if (in_block && length(cur) > 0) blocks[[length(blocks) + 1]] <- cur
}

# Flatten blocks, do light cleanup: remove leading line numbers if present (e.g., '1: x <- 2')
clean_line <- function(ln) {
  # remove listing line numbers like '  1. ' or '1 ' or '1:' at start
  ln <- sub("^\\s*\\d+[:\.\\)]?\\s*", "", ln)
  # replace any non-ASCII whitespace sequences
  ln <- gsub("\t", " ", ln)
  ln
}

code_lines <- character(0)
for (b in blocks) {
  cleaned <- vapply(b, clean_line, FUN.VALUE = "")
  code_lines <- c(code_lines, cleaned, "")
}

if (length(code_lines) == 0) {
  cat("No code-like lines found with heuristics.\n")
  cat("You can run this script locally and adjust the heuristics in 'is_code_line'.\n")
} else {
  # Write to output file
  hdr <- c(
    "# Combined R programs extracted (heuristically) from Lab 11 Answers.pdf",
    paste0("# Source: ", pdf_url),
    "# NOTE: This file was generated by lab11_programs.R — please review and tidy up.",
    "\n"
  )
  writeLines(c(hdr, code_lines), con = out_file)
  cat("Wrote extracted code to:", out_file, "\n")
}

